#!/usr/bin/env python3
"""Rasterize the navigation SVG sources to row-major MSB-first 1bpp masks.

Only the explicit circle/polyline subset used by these original icons is
supported; unsupported edits fail instead of silently dropping geometry.
No third-party modules or runtime image decoders are required.
"""

import argparse
import math
from pathlib import Path
import xml.etree.ElementTree as ET


NAMES = ('home', 'time', 'word', 'note', 'todo', 'ai', 'settings')
ROOT = Path(__file__).resolve().parents[2]


def distance(x, y, a, b):
    dx, dy = b[0] - a[0], b[1] - a[1]
    length = dx * dx + dy * dy
    if not length:
        return math.hypot(x - a[0], y - a[1])
    t = max(0, min(1, ((x - a[0]) * dx + (y - a[1]) * dy) / length))
    return math.hypot(x - a[0] - t * dx, y - a[1] - t * dy)


def rasterize(path):
    root = ET.parse(path).getroot()
    assert root.attrib['viewBox'] == '0 0 24 24', path
    shapes = []
    for element in root.iter():
        tag = element.tag.rsplit('}', 1)[-1]
        if tag == 'g':
            assert element.attrib == dict(fill='none', stroke='#000', **{
                'stroke-width': '2', 'stroke-linecap': 'round', 'stroke-linejoin': 'round'}), path
        elif tag == 'circle':
            shapes.append(('C', tuple(float(element.attrib[k]) for k in ('cx', 'cy', 'r'))))
        elif tag == 'polyline':
            shapes.append(('L', [tuple(map(float, p.split(',')))
                                 for p in element.attrib['points'].split()]))
        elif tag not in ('svg', 'title'):
            raise ValueError(f'Unsupported SVG element: {tag} in {path}')
        if any(k in element.attrib for k in ('transform', 'style')):
            raise ValueError(f'Unsupported SVG transform/style in {path}')

    def ink(x, y):
        for kind, shape in shapes:
            if kind == 'C':
                cx, cy, r = shape
                if abs(math.hypot(x - cx, y - cy) - r) <= 1:
                    return True
            elif any(distance(x, y, a, b) <= 1 for a, b in zip(shape, shape[1:])):
                return True
        return False

    data = []
    for y in range(24):
        for x in range(0, 24, 8):
            data.append(sum((0x80 >> bit) if ink(x + bit + 0.5, y + 0.5) else 0
                            for bit in range(8)))
    return data


def generated():
    lines = ['#pragma once', '', '// Generated by tools/ui/generate_navigation_icons.py; edit navigation/*.svg.',
             '#include "wqn_bitmap_asset.h"', '', 'namespace device_ui_internal {', '']
    for name in NAMES:
        data = rasterize(ROOT / 'main/ui/assets/navigation' / f'{name}.svg')
        lines.append(f'inline constexpr uint8_t kNavigation_{name}_bits[] = {{')
        for offset in range(0, len(data), 12):
            lines.append('    ' + ', '.join(f'0x{b:02x}' for b in data[offset:offset + 12]) + ',')
        lines.extend(['};', f'inline constexpr WqnBitmapAsset kNavigation_{name} = {{',
                      f'    24, 24, 3, sizeof(kNavigation_{name}_bits), kNavigation_{name}_bits', '};', ''])
    lines.append('inline constexpr const WqnBitmapAsset* kNavigationIcons[] = {')
    lines.extend(f'    &kNavigation_{name},' for name in NAMES)
    lines.extend(['};', '', '}  // namespace device_ui_internal', ''])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'main/ui/assets/navigation_icons.h'
    content = generated()
    if args.check:
        if not target.is_file() or target.read_text() != content:
            raise SystemExit('FAIL: navigation icons differ; regenerate from SVG sources')
        print('PASS: navigation icon header matches seven SVGs (504 B raw 1bpp)')
    else:
        target.write_text(content)
        print(f'Generated {target}')


if __name__ == '__main__':
    main()
